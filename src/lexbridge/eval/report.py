"""Render reports/ablation.md from the run files. Never edited by hand."""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path

from lexbridge.eval.metrics import KS, MACRO
from lexbridge.eval.run import RUNS, RunRecord

TABLE = Path("reports/ablation.md")
HEADER = """\
# Retrieval ablation

Generated by `python -m lexbridge.eval.run` from `reports/runs/*.json`; do not edit.
Scores are macro means: every category weighs the same, so the 534 generated map lookups
do not drown the 28 hand-written lay questions. `wrong-regime@1` is the share of dated
questions whose first result is the right provision from the wrong code (lower is better).
Topical cases are templated from section headings and overstate real-world quality; the
lay, Hindi, boundary and tricky rows are the hand-written test.
"""
# A run without a score for a column, e.g. a retriever with no embedder.
MISSING = "-"


def _percent(value: float | None) -> str:
    return MISSING if value is None else f"{value * 100:.1f}"


def render(runs: Sequence[RunRecord]) -> str:
    lines = [HEADER, "## Overall (macro)", "",
             "| run | embedder | " + " | ".join(f"hit@{k}" for k in KS)
             + " | MRR | wrong-regime@1 | query p50 / p95 ms |",
             "|---|---|" + "---:|" * (len(KS) + 3)]
    for run in runs:
        macro, latency = run["scores"][MACRO], run["query_ms"]
        lines.append(
            f"| {run['name']} | {run['embedder'] or MISSING} | "
            + " | ".join(_percent(macro[f"hit@{k}"]) for k in KS)
            + f" | {_percent(macro['mrr'])} | {_percent(macro['wrong_regime@1'])}"
            + f" | {latency['p50']} / {latency['p95']} |")

    categories = sorted({c for run in runs for c in run["scores"] if c != MACRO})
    lines += ["", "## hit@5 by category", "",
              "| run | " + " | ".join(categories) + " |",
              "|---|" + "---:|" * len(categories)]
    for run in runs:
        scores = run["scores"]
        lines.append(f"| {run['name']} | " + " | ".join(
            _percent(scores[c]["hit@5"]) if c in scores else MISSING for c in categories) + " |")
    counts = {c: s["n"] for run in runs[-1:] for c, s in run["scores"].items() if c != MACRO}
    lines += ["", "Cases per category: "
              + ", ".join(f"{c} {n}" for c, n in sorted(counts.items())) + "."]
    return "\n".join(lines) + "\n"


def write_table(runs_dir: Path = RUNS, table: Path = TABLE) -> Path:
    runs: list[RunRecord] = [json.loads(p.read_text(encoding="utf-8"))
                             for p in sorted(runs_dir.glob("*.json"))]
    table.write_text(render(runs), encoding="utf-8", newline="\n")
    return table
